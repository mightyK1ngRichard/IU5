-- Скрипт 02: создание таблиц без индексов (контрольная БД)
-- Предметная область: детская спортивная школа
-- Выполнять в базе sport_school_noidx
-- =====================================================================

DROP TABLE IF EXISTS trainings CASCADE;
DROP TABLE IF EXISTS students  CASCADE;

-- ---------------------------------------------------------------------
-- tab1: ученики (внешняя таблица WHERE-запроса)
-- ---------------------------------------------------------------------
CREATE TABLE students (
    student_id  BIGSERIAL PRIMARY KEY,
    full_name   TEXT      NOT NULL,
    birth_date  DATE      NOT NULL,
    -- индексное поле в "копии с индексами" — массив видов спорта,
    -- которые посещает ребёнок. На массив будет навешен GIN.
    disciplines TEXT[]    NOT NULL
);

COMMENT ON TABLE  students             IS 'Ученики спортивной школы (tab1)';
COMMENT ON COLUMN students.disciplines IS 'Массив секций (для GIN-индекса в копии с индексами)';

-- ---------------------------------------------------------------------
-- tab2: журнал тренировок (подзапросная таблица)
-- ---------------------------------------------------------------------
CREATE TABLE trainings (
    training_id   BIGSERIAL  PRIMARY KEY,
    student_id    BIGINT     NOT NULL,
    discipline    TEXT       NOT NULL,
    -- индексное поле в "копии с индексами" — дата/время тренировки.
    -- Записи вставляются в порядке возрастания training_date,
    -- поэтому физический порядок строк хорошо коррелирует с этим полем,
    -- что является обязательным условием эффективной работы BRIN.
    training_date TIMESTAMP  NOT NULL,
    duration_min  INT        NOT NULL
);

COMMENT ON TABLE  trainings               IS 'Журнал посещений тренировок (tab2)';
COMMENT ON COLUMN trainings.training_date IS 'Дата/время тренировки (для BRIN-индекса в копии с индексами)';

-- В копии БЕЗ индексов первичные ключи всё же создают системные B-tree.
-- Это не влияет на эксперимент, т.к. в WHERE используются другие поля
-- (disciplines и training_date), на которые здесь индексов нет.
